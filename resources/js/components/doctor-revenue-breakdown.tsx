import * as React from "react";
import { router } from "@inertiajs/react";
import {
    IndianRupeeIcon,
    XIcon,
    StethoscopeIcon,
    UsersIcon,
    CheckCircle2Icon,
} from "lucide-react";
import {
    Card,
    CardContent,
    CardDescription,
    CardHeader,
    CardTitle,
} from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { cn } from "@/lib/utils";

export interface DoctorRevenueItem {
    id: number;
    name: string;
    specialty: string;
    room?: string;
    revenue: number;
    formattedRevenue: string;
    leadsCount: number;
    appointmentsCount: number;
    consultationFee: number;
    percentageOfTotal: number;
}

interface DoctorRevenueBreakdownProps {
    doctorRevenues?: DoctorRevenueItem[];
    selectedDoctorId?: number | null;
}

export function DoctorRevenueBreakdown({
    doctorRevenues = [],
    selectedDoctorId,
}: DoctorRevenueBreakdownProps) {
    if (!doctorRevenues || doctorRevenues.length === 0) {
        return null;
    }

    const totalRevenue = doctorRevenues.reduce((acc, d) => acc + d.revenue, 0);

    const handleFilterDoctor = (doctorId: number) => {
        if (selectedDoctorId === doctorId) {
            router.visit("/dashboard");
        } else {
            router.visit(`/dashboard?doctor_id=${doctorId}`);
        }
    };

    const handleClearFilter = () => {
        router.visit("/dashboard");
    };

    return (
        <Card className="mx-4 lg:mx-6 border shadow-xs bg-card">
            <CardHeader className="flex flex-col gap-2 sm:flex-row sm:items-center sm:justify-between pb-3">
                <div className="flex items-center gap-3">
                    <div className="flex size-10 shrink-0 items-center justify-center rounded-lg bg-emerald-500/10 text-emerald-600 dark:bg-emerald-500/20 dark:text-emerald-400">
                        <IndianRupeeIcon className="size-5" />
                    </div>
                    <div>
                        <div className="flex items-center gap-2">
                            <CardTitle className="text-base sm:text-lg font-semibold tracking-tight text-foreground">
                                Doctor-Wise Revenue Breakdown
                            </CardTitle>
                            <Badge
                                variant="outline"
                                className="text-[10px] bg-primary/5 text-primary border-primary/20"
                            >
                                Admin View
                            </Badge>
                        </div>
                        <CardDescription className="text-xs text-muted-foreground mt-0.5">
                            Individual revenue and consultation billings generated by each clinic specialist.
                        </CardDescription>
                    </div>
                </div>

                <div className="flex items-center gap-2">
                    {selectedDoctorId && (
                        <Button
                            variant="ghost"
                            size="sm"
                            onClick={handleClearFilter}
                            className="h-8 text-xs text-muted-foreground hover:text-foreground cursor-pointer gap-1"
                        >
                            <XIcon className="size-3.5" />
                            Clear Filter
                        </Button>
                    )}
                    <Badge
                        variant="secondary"
                        className="text-xs px-2.5 py-1 font-medium tabular-nums"
                    >
                        Total Clinic Revenue: ₹
                        {totalRevenue.toLocaleString(undefined, {
                            minimumFractionDigits: 2,
                            maximumFractionDigits: 2,
                        })}
                    </Badge>
                </div>
            </CardHeader>

            <CardContent className="pt-0">
                <div className="grid grid-cols-1 gap-3 sm:grid-cols-2 lg:grid-cols-4">
                    {doctorRevenues.map((doc) => {
                        const isSelected = selectedDoctorId === doc.id;
                        const initials =
                            doc.name
                                .replace("Dr. ", "")
                                .split(" ")
                                .filter(Boolean)
                                .slice(0, 2)
                                .map((n) => n[0])
                                .join("")
                                .toUpperCase() || "DR";

                        return (
                            <div
                                key={doc.id}
                                onClick={() => handleFilterDoctor(doc.id)}
                                className={cn(
                                    "flex flex-col justify-between p-3.5 rounded-xl border transition-all cursor-pointer",
                                    isSelected
                                        ? "border-primary bg-primary/5 ring-2 ring-primary/20 shadow-xs"
                                        : "border-border/60 bg-muted/20 hover:border-primary/40 hover:bg-muted/40 hover:shadow-xs"
                                )}
                            >
                                <div className="flex flex-col gap-2">
                                    <div className="flex items-start justify-between gap-2">
                                        <div className="flex items-center gap-2.5 min-w-0">
                                            <div className="flex size-8 shrink-0 items-center justify-center rounded-lg bg-primary/10 text-primary font-bold text-xs">
                                                {initials}
                                            </div>
                                            <div className="min-w-0">
                                                <div className="font-semibold text-xs text-foreground truncate">
                                                    {doc.name}
                                                </div>
                                                <div className="text-[11px] text-muted-foreground truncate">
                                                    {doc.specialty}
                                                </div>
                                            </div>
                                        </div>
                                        {isSelected && (
                                            <Badge className="text-[10px] bg-primary text-primary-foreground shrink-0 py-0 px-1.5 h-5">
                                                Filtered
                                            </Badge>
                                        )}
                                    </div>

                                    <div className="mt-2">
                                        <div className="text-xl font-bold tracking-tight text-foreground tabular-nums">
                                            {doc.formattedRevenue}
                                        </div>
                                        <div className="flex items-center justify-between text-[11px] text-muted-foreground mt-1">
                                            <span>Share of Clinic</span>
                                            <span className="font-semibold text-foreground/90 tabular-nums">
                                                {doc.percentageOfTotal}%
                                            </span>
                                        </div>
                                        {/* Progress Bar */}
                                        <div className="w-full bg-muted-foreground/15 rounded-full h-1.5 mt-1.5 overflow-hidden">
                                            <div
                                                className="bg-emerald-600 dark:bg-emerald-500 h-1.5 rounded-full transition-all duration-300"
                                                style={{
                                                    width: `${Math.max(
                                                        doc.percentageOfTotal,
                                                        doc.revenue > 0 ? 5 : 0
                                                    )}%`,
                                                }}
                                            />
                                        </div>
                                    </div>
                                </div>

                                <div className="flex items-center justify-between pt-3 mt-3 border-t border-border/50 text-[11px] text-muted-foreground">
                                    <span>
                                        {doc.leadsCount}{" "}
                                        {doc.leadsCount === 1 ? "Lead" : "Leads"}
                                    </span>
                                    <span>
                                        Fee: ₹
                                        {Number(
                                            doc.consultationFee
                                        ).toLocaleString()}
                                    </span>
                                </div>
                            </div>
                        );
                    })}
                </div>
            </CardContent>
        </Card>
    );
}
